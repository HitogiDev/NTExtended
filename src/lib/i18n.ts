const catalogs = { en, es } as const;

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function resolveLanguage(setting: Settings['language']): 'en' | 'es' {
  if (setting !== 'auto') return setting;
  return browser.i18n.getUILanguage().toLowerCase().startsWith('es') ? 'es' : 'en';
}

/** Translate the error codes of the API client. Server messages stay unchanged. */
export function translateError(t: Translate, error: string | undefined): string {
  if (error === 'network') return t('error.network');
  if (error === 'not-connected') return t('drafts.notConnected');
  return error ?? '';
}

export function createTranslator(language: 'en' | 'es'): Translate {
  const catalog = catalogs[language];
  return (key, vars) => {
    let text: string = catalog[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
}
